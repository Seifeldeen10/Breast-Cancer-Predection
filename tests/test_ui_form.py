# tests/test_ui_form.py
"""Tests for Streamlit UI form configuration, structured choices, and model compatibility.

Verifies:
1. Every categorical dropdown returns a valid training category.
2. Binary choices map correctly to model input values.
3. Numeric inputs remain numeric with bounded ranges and valid steps.
4. Unknown or missing values are handled correctly by the pipeline.
5. The prediction function works cleanly with payloads generated by the new form.
6. No unexpected free-text fields remain for categorical features.
7. Required research disclaimer is present.
"""

import ast
from pathlib import Path
import joblib
import pandas as pd
import pytest

from src.predict.predict import predict
from src.webapp.form_config import (
    BINARY_CONFIG,
    CATEGORICAL_OPTIONS,
    MULTI_CAT_CONFIG,
    NUMERIC_CONFIG,
    calculate_bmi,
    format_form_payload,
)

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = PROJECT_ROOT / "data" / "raw" / "BCRSD_30K.csv"
MODEL_PATH = PROJECT_ROOT / "models" / "risk_pre_pipeline.pkl"
APP_PATH = PROJECT_ROOT / "src" / "webapp" / "app.py"


@pytest.fixture(scope="module")
def dataset_df():
    """Load training dataset to verify categorical values."""
    return pd.read_csv(DATA_PATH)


@pytest.fixture(scope="module")
def pipeline():
    """Load trained risk pre-pipeline."""
    return joblib.load(MODEL_PATH)


def test_categorical_dropdown_options_match_training_data(dataset_df, pipeline):
    """Every categorical dropdown/radio option must match the actual dataset categories."""
    ohe = pipeline.named_steps["preprocess"].named_transformers_["cat"].named_steps["onehot"]
    cat_feature_names = pipeline.named_steps["preprocess"].transformers_[1][2]
    ohe_categories_by_feature = {col: list(cats) for col, cats in zip(cat_feature_names, ohe.categories_)}

    for feature_name, options in CATEGORICAL_OPTIONS.items():
        assert feature_name in dataset_df.columns, f"Feature '{feature_name}' not in dataset"
        dataset_uniques = dataset_df[feature_name].dropna().unique().tolist()

        # Every UI option must exist in the actual dataset unique values
        for opt in options:
            assert opt in dataset_uniques, (
                f"Option '{opt}' for feature '{feature_name}' is not in training dataset: {dataset_uniques}"
            )

        # Every UI option must also be recognized by the pipeline's OneHotEncoder
        if feature_name in ohe_categories_by_feature:
            ohe_cats = ohe_categories_by_feature[feature_name]
            assert set(options) == set(ohe_cats), (
                f"Options for '{feature_name}' ({options}) do not match OneHotEncoder ({ohe_cats})"
            )


