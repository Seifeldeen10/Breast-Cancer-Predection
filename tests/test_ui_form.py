def test_prediction_works_with_new_form():
    """Predict function must execute successfully with selections from the new form."""
    sample_inputs = {}
    for feat, cfg in NUMERIC_CONFIG.items():
        sample_inputs[feat] = (cfg["min_value"] + cfg["max_value"]) / 2.0 if not cfg["is_integer"] else int((cfg["min_value"] + cfg["max_value"]) // 2)

    for feat, cfg in BINARY_CONFIG.items():
        sample_inputs[feat] = cfg["options"][0]

    for feat, cfg in MULTI_CAT_CONFIG.items():
        sample_inputs[feat] = cfg["options"][0]

    formatted = format_form_payload(sample_inputs)
    result = predict(formatted)

    assert isinstance(result, dict)
    assert result["prediction"] in ["Low", "Moderate", "High"]
    assert isinstance(result["scores"], dict)
    assert set(result["scores"].keys()) == {"High", "Low", "Moderate"}
    total_score = sum(result["scores"].values())
    assert pytest.approx(total_score, rel=1e-3) == 1.0


def test_no_unexpected_free_text_fields_remain_for_categorical():
    """The webapp must NOT use st.text_input for any categorical or binary feature."""
    app_source = APP_PATH.read_text(encoding="utf-8")
    tree = ast.parse(app_source)

    # Search for calls to st.text_input
    text_input_calls = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Attribute) and func.attr == "text_input":
                text_input_calls.append(node)

    assert len(text_input_calls) == 0, (
        f"Found {len(text_input_calls)} free-text 'st.text_input' calls in {APP_PATH}; "
        "all categorical and numeric features must use structured widgets."
    )


def test_bmi_auto_calculation():
    """BMI must ALWAYS be correctly computed from height and weight."""
    # Example: 70kg, 175cm -> 70 / (1.75^2) = 22.86
    calc = calculate_bmi(175.0, 70.0)
    assert calc == 22.86

    # When height and weight are provided, BMI is always calculated automatically
    payload_without_bmi = {"Height_cm": 175.0, "Weight_kg": 70.0}
    formatted = format_form_payload(payload_without_bmi)
    assert formatted["BMI"] == 22.86

    # Even if an existing/stale BMI was present, it is automatically recalculated
    payload_with_stale_bmi = {"Height_cm": 175.0, "Weight_kg": 70.0, "BMI": 99.0}
    formatted_recalc = format_form_payload(payload_with_stale_bmi)
    assert formatted_recalc["BMI"] == 22.86


