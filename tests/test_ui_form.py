def test_numeric_inputs_remain_numeric(dataset_df, pipeline):
    """All 8 numeric fields must remain numeric (int or float) with appropriate bounds."""
    expected_numerics = [
        "Age",
        "Height_cm",
        "Weight_kg",
        "BMI",
        "Age_First_Menstruation",
        "Age_First_Pregnancy",
        "Parity",
        "Sleep_Hours",
    ]

    assert set(NUMERIC_CONFIG.keys()) == set(expected_numerics)

    for feat in expected_numerics:
        cfg = NUMERIC_CONFIG[feat]
        min_val = cfg["min_value"]
        max_val = cfg["max_value"]
        step = cfg["step"]

        assert isinstance(min_val, (int, float)), f"{feat} min_value must be numeric"
        assert isinstance(max_val, (int, float)), f"{feat} max_value must be numeric"
        assert isinstance(step, (int, float)), f"{feat} step must be numeric"
        assert min_val < max_val, f"{feat} min_value ({min_val}) must be < max_value ({max_val})"
        assert step > 0, f"{feat} step must be positive"

        # Check bounds cover typical dataset percentiles
        ds_col = dataset_df[feat]
        assert min_val <= ds_col.quantile(0.01), f"{feat} min_value ({min_val}) exceeds 1st percentile"
        assert max_val >= ds_col.quantile(0.99), f"{feat} max_value ({max_val}) below 99th percentile"


